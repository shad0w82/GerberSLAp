"""EAGLE. Only the current export is supported (EAGLE 9 and later, and Fusion's electronics: `CAMOutputs/GerberFiles`,
files named `copper_top.gbr`, `soldermask_top.gbr`, `profile.gbr`, drill files `.xln` that state their number format).

The old export made by the CAM Processor (`.GTL`, `.GBL`, `.GML`, `.TXT`, with `.dri` and `.gpi` information files) is
refused: its drill file states only "inches" and leaves the number format to convention (EAGLE writes 2.5; the usual
assumption is 2.4, and the holes land ten times too far, without any error), and its outline is drawn with a zero-width
aperture. It is recognised by the files EAGLE's old CAM Processor writes next to the layers, and by its header."""
import re

from .base import Incompatible, Recognizer
from .sniff import software

_CAM_INFO = re.compile(r"Generated by EAGLE CAM Processor[ \t]*([\d.]*)")
_OLD_HEADER = re.compile(r"\AG75\*[ \t]*\r?\n%MO(?:IN|MM)\*%[ \t]*\r?\n%OFA0B0\*%")


class EagleRecognizer(Recognizer):
    name = "eagle"

    def check(self, probes) -> None:
        for p in probes:
            m = _CAM_INFO.match(p.head.lstrip())
            if m:
                raise Incompatible("old EAGLE CAM Processor export", params={
                    "cad": "eagle", "reason": "old_cam_processor", "version": m.group(1) or None, "file": p.basename})
            if p.kind == "gerber" and _OLD_HEADER.match(p.head):
                raise Incompatible("old EAGLE CAM Processor export", params={
                    "cad": "eagle", "reason": "old_cam_header", "version": None, "file": p.basename})

    def score(self, probes) -> float:
        return 1.0 if "eagle" in software(probes) else 0.0
